/** One blueprint atlas pack (original `blueprint.atlases[i]`), URLs already mapped to local public files. */
export interface WorkGridAtlas {
  type: 'image' | 'video';
  mediaAtlas: string;
  mediaAlphaAtlas: string;
  labelsAtlas: string;
}

/** Filter values of a tile (original `P(doc.data)`, module 55607). Olwtelet: zones = project kind (web, jogo),
 * features = categories, clients = ['olwtelet'], services unused. */
export interface WorkGridTileFilters {
  services: string[];
  zones: string[];
  clients: string[];
  features: string[];
}

/**
 * One grid tile (original tile object built from `gridContent` + `blueprint.cells`, module 55607 L3068-3086).
 * `cell` = [cellX, cellY] of the blueprint atlas cell (cellX = atlas ROW from the top, cellY = COLUMN).
 */
export interface WorkGridTile {
  atlasIndex: number;
  slug: string;
  id: string;
  launchDate: string;
  cell: [number, number];
  filters: WorkGridTileFilters;
  /** 'published' | 'in-development' */
  status: string;
  /** index in the 11×11 spiral (0 = just below-left of the screen centre); each project appears once per period */
  slot: number;
}

/** One intentional empty-cell design of the atlas (lines, intervals, a dark surface): never clickable, never hovered. */
export interface WorkGridEmptyCell {
  variant: string;
  cell: [number, number];
  atlasIndex: number;
}

/** Intro (pixel mosaic + particle mark) assets: local public URLs generated by scripts/brand/build-brand-assets.mjs. */
export interface WorkGridIntro {
  /** `/assets/intro/` */
  frameBase: string;
  /** desktop sets (`set{1..n}/{0..24}.webp`, 1920×1080): the Olwtelet mark lit in one material per set */
  desktopSets: number;
  /** mobile sets (`mobile/set{1..n}/{0..24}.webp`, 1080×1920) */
  mobileSets: number;
  /** 25 frames per set */
  framesPerSet: number;
  /** `/assets/models/olwtelet-mark.glb`: point cloud sampled from the mark's faces */
  markUrl: string;
  /** `/assets/images/particle.jpg` (brand-neutral sprite) */
  particleUrl: string;
}

export interface WorkGridData {
  atlases: WorkGridAtlas[];
  /** one tile per project (published and in development), each at its own spiral slot */
  tiles: WorkGridTile[];
  /** the empty-cell designs; every slot without a (matching) project shows one of them */
  empty: WorkGridEmptyCell[];
  intro: WorkGridIntro;
  [key: string]: unknown;
}
